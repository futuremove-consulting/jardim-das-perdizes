import "@testing-library/jest-dom/vitest";

// jsdom does not implement matchMedia; the theme layer needs it to resolve the
// OS preference. Default to "light" so tests are deterministic.
if (typeof window !== "undefined" && !window.matchMedia) {
  Object.defineProperty(window, "matchMedia", {
    writable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => false,
    }),
  });
}

